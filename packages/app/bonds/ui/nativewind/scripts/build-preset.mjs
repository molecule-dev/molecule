#!/usr/bin/env node
/**
 * Builds `dist/preset.cjs` (the Tailwind v3 preset, `@molecule/app-ui-nativewind/preset`):
 * copies `src/preset.cjs` and writes `dist/preset-tokens.cjs`, the token names and
 * light defaults taken from `@molecule/app-ui-tailwind`'s token table, and
 * `dist/device-classes.cjs`, the classes the device rewrite produces that no file names
 * (scripts/device-classes.mjs). Runs after `tsc` in `npm run build`. Tailwind v3 loads its
 * config with `require`, so the preset is CommonJS with its data baked in.
 *
 * @module
 */

import console from 'node:console'
import { copyFileSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, URL } from 'node:url'

import { colorTokens, themeVariables } from '@molecule/app-ui-tailwind'

import { forDevice } from '../dist/device.js'
import { FONT_SIZE_VARIANTS, lineHeightClass, WEB_FONT_SIZES } from '../dist/fontSizes.js'
import { deviceOnlyClasses, flexRowClasses, inlineSourceClasses } from './device-classes.mjs'

const dist = fileURLToPath(new URL('../dist/', import.meta.url))
mkdirSync(dist, { recursive: true })
copyFileSync(fileURLToPath(new URL('../src/preset.cjs', import.meta.url)), `${dist}preset.cjs`)

const data = {
  names: colorTokens.map((token) => token.name),
  defaults: themeVariables(),
}
writeFileSync(
  `${dist}preset-tokens.cjs`,
  [
    "// GENERATED by scripts/build-preset.mjs from @molecule/app-ui-tailwind's token table; do not edit.",
    "'use strict'",
    '',
    `module.exports = ${JSON.stringify(data, null, 2)}`,
    '',
  ].join('\n'),
)
console.log(`preset: ${data.names.length} colour tokens`)

writeFileSync(
  `${dist}preset-font-sizes.cjs`,
  [
    '// GENERATED by scripts/build-preset.mjs from src/fontSizes.ts; do not edit.',
    "'use strict'",
    '',
    `module.exports = ${JSON.stringify(WEB_FONT_SIZES, null, 2)}`,
    '',
  ].join('\n'),
)

const webDist = dirname(fileURLToPath(import.meta.resolve('@molecule/app-ui-tailwind')))
const webFiles = readdirSync(webDist, { recursive: true })
  .filter((file) => /\.c?js$/.test(file))
  .map((file) => readFileSync(join(webDist, file), 'utf8'))
// The classes the web ClassMap builds at run time (`text-${size}`): base.css lists them for Tailwind 4
// with `@source inline()`, which Tailwind 3 does not read.
const webCss = readFileSync(join(webDist, '..', 'base.css'), 'utf8')
const inlineClasses = inlineSourceClasses(webCss).flatMap((cls) => forDevice(cls).split(/\s+/))
const deviceClasses = [
  ...new Set([
    ...deviceOnlyClasses(webFiles, forDevice),
    ...inlineClasses.filter(Boolean),
    // The direction of a flex container that names none, which splitForNative writes at run time.
    ...flexRowClasses([...webFiles, inlineClasses.join(' ')]),
    // The line height alone of an inherited size, which splitForNative writes at run time.
    ...Object.keys(WEB_FONT_SIZES).flatMap((name) =>
      FONT_SIZE_VARIANTS.map((variant) => `${variant}${lineHeightClass(name)}`),
    ),
  ]),
].sort()
writeFileSync(
  `${dist}device-classes.cjs`,
  [
    '// GENERATED by scripts/build-preset.mjs; do not edit. The classes the device ClassMap',
    '// returns that no file of the web ClassMap names (`space-y-2` becomes `gap-y-2` at run',
    '// time; `text-${size}`, which base.css lists with @source inline). Tailwind generates a',
    '// rule only for a class it finds in a scanned file.',
    "'use strict'",
    '',
    `module.exports = ${JSON.stringify(deviceClasses, null, 2)}`,
    '',
  ].join('\n'),
)
console.log(`preset: ${deviceClasses.length} device-only classes`)
