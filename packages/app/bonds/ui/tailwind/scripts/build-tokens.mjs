#!/usr/bin/env node
/**
 * Writes `src/tokens.generated.ts`: the colour tokens and check marks of `base.css`,
 * as data JavaScript can use without a CSS engine.
 *
 *   node scripts/build-tokens.mjs           regenerate the file
 *   node scripts/build-tokens.mjs --check   exit 1 when the committed file differs
 *   --base <file>                           read another stylesheet (tests)
 *
 * `base.css` stays the one source: a token is `core` (read from the theme bond's
 * `--mol-color-*`, with a default), `mix` (a `color-mix(in srgb, …)` of two
 * operands) or `alias` (another token). Any other form throws, so a new kind of
 * value cannot be dropped silently.
 *
 * @module
 */

import console from 'node:console'
import { readFileSync, writeFileSync } from 'node:fs'
import process from 'node:process'
import { fileURLToPath, URL } from 'node:url'

import prettier from 'prettier'

const BASE_CSS = fileURLToPath(new URL('../base.css', import.meta.url))
const OUT = fileURLToPath(new URL('../src/tokens.generated.ts', import.meta.url))

/**
 * Reads one `color-mix` or alias operand.
 *
 * @param {string} text - `var(--color-x)`, `var(--color-x, #fff)`, `black` or `#hex`.
 * @returns {{ ref: string, fallback?: string } | { literal: string }} The operand.
 */
function operand(text) {
  const value = text.trim()
  const ref = /^var\(--color-([\w-]+)(?:\s*,\s*([^)]+))?\)$/.exec(value)
  if (ref) return ref[2] ? { ref: ref[1], fallback: ref[2].trim() } : { ref: ref[1] }
  if (/^var\(/.test(value)) throw new Error(`base.css @theme: an operand reads ${value}`)
  return { literal: value }
}

/**
 * Parses the colour tokens of a stylesheet's `@theme` block.
 *
 * @param {string} css - The stylesheet (`base.css`).
 * @returns {object[]} The tokens, in declaration order.
 */
export function parseColorTokens(css) {
  const text = css.replace(/\/\*[\s\S]*?\*\//g, '')
  const start = text.indexOf('@theme {')
  if (start === -1) throw new Error('base.css has no @theme block')
  const body = text.slice(start + '@theme {'.length, text.indexOf('\n}', start))
  const tokens = []
  for (const match of body.matchAll(/--([\w-]+):\s*([^;]+);/g)) {
    const [, property, raw] = match
    if (!property.startsWith('color-')) continue
    const name = property.slice('color-'.length)
    const value = raw.replace(/\s+/g, ' ').trim()
    const core = /^var\(--mol-color-([\w-]+),\s*(.+)\)$/.exec(value)
    const mix = /^color-mix\(\s*in srgb,\s*(.+?)\s+([\d.]+)%,\s*(.+?)\s*\)$/.exec(value)
    if (core) {
      // The ThemeColors key the theme bond writes as --mol-color-<kebab-case key>.
      const themeKey = core[1].replace(/-([a-z])/g, (_, c) => c.toUpperCase())
      tokens.push({ name, kind: 'core', themeKey, default: core[2].trim() })
    } else if (mix) {
      tokens.push({
        name,
        kind: 'mix',
        a: operand(mix[1]),
        percent: Number(mix[2]),
        b: operand(mix[3]),
      })
    } else if (/^var\(--color-/.test(value)) {
      tokens.push({ name, kind: 'alias', ...operand(value) })
    } else {
      throw new Error(
        `base.css @theme: --${property} has a form the token table cannot express: ${value}`,
      )
    }
  }
  return tokens
}

/**
 * Reads each form-control mark path from its SVG mask in the stylesheet.
 *
 * @param {string} css - The ClassMap stylesheet.
 * @returns {Record<string, string>} The paths by mark name.
 */
function parseCheckMarks(css) {
  const paths = {}
  for (const name of ['checked', 'mixed', 'radio']) {
    const token = new RegExp(`--mol-check-mark-${name}:\\s*url\\("([^"]+)"\\);`).exec(css)
    const path = token && /<path d='([^']+)'/.exec(decodeURIComponent(token[1]))?.[1]
    if (!path) throw new Error(`base.css: missing path for --mol-check-mark-${name}`)
    paths[name] = path
  }
  return paths
}

/**
 * Renders the TypeScript module for the tokens and marks.
 *
 * @param {object[]} tokens - The parsed tokens.
 * @param {Record<string, string>} marks - The check mark paths.
 * @returns {Promise<string>} The module source, formatted the way the repository formats it.
 */
export async function renderTokensModule(tokens, marks) {
  const keys = tokens.filter((t) => t.kind === 'core').map((t) => t.themeKey)
  const lines = [
    '/**',
    " * The colour tokens and check marks of this package's `base.css`, as data.",
    ' *',
    ' * GENERATED by `scripts/build-tokens.mjs` from `base.css`; do not edit. A test',
    ' * regenerates it and fails when `base.css` changed without it.',
    ' *',
    ' * @module',
    ' */',
    '',
    "import type { ColorToken } from './types.js'",
    '',
    '/** The `ThemeColors` keys a core token reads (the theme bond writes each as `--mol-color-<key>`). */',
    `export type ThemeColorTokenKey =\n${[...new Set(keys)].map((k) => `  | '${k}'`).join('\n')}`,
    '',
    '/** Every colour token of `base.css`, in declaration order. */',
    `export const colorTokens: readonly ColorToken<ThemeColorTokenKey>[] = ${JSON.stringify(tokens, null, 2)}`,
    '',
    '/** Paths that the web stylesheet and native check fields draw in a 16×16 view box. */',
    `export const checkMarkPaths = ${JSON.stringify(marks, null, 2)} as const`,
    '',
  ]
  const options = await prettier.resolveConfig(OUT)
  return prettier.format(lines.join('\n'), { ...options, filepath: OUT })
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]
if (isMain) {
  const at = process.argv.indexOf('--base')
  const base = at === -1 ? BASE_CSS : process.argv[at + 1]
  const css = readFileSync(base, 'utf8')
  const source = await renderTokensModule(parseColorTokens(css), parseCheckMarks(css))
  if (process.argv.includes('--check')) {
    let committed = ''
    try {
      committed = readFileSync(OUT, 'utf8')
    } catch (_error) {
      // A missing file is drift too; the comparison below reports it.
    }
    if (committed !== source) {
      console.error(
        'src/tokens.generated.ts does not match base.css. Run `npm run gen:tokens` in packages/app/bonds/ui/tailwind and commit it.',
      )
      process.exit(1)
    }
  } else {
    writeFileSync(OUT, source)
  }
}
