"""
Builds what React Native needs to draw Material Symbols from the web font this package ships
(fonts/MaterialSymbolsOutlined.woff2): React Native draws neither ligatures nor variable axes, so a
device draws each icon by its codepoint, from static instances of the font.

Writes:
  fonts/MaterialSymbolsOutlined.ttf         FILL 0, wght 400, GRAD 0, opsz 24 (base.css's axes)
  fonts/MaterialSymbolsOutlined-Filled.ttf  the same with FILL 1
  src/glyphs.data.ts                        every glyph name the font draws, with its codepoint

Run it whenever the woff2 changes (src/__tests__/glyphs.test.ts compares the woff2's hash with the
one recorded in src/glyphs.data.ts):

  python3 -m venv .venv && .venv/bin/pip install fonttools brotli
  .venv/bin/python scripts/build-native-fonts.py
"""

import hashlib
import pathlib

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'fonts' / 'MaterialSymbolsOutlined.woff2'
AXES = {'wght': 400, 'GRAD': 0, 'opsz': 24}


def ligature_codepoints(font: TTFont) -> dict[str, int]:
    """Each glyph name the font draws by ligature, with the codepoint of the same glyph."""
    by_glyph: dict[str, int] = {}
    for codepoint, glyph in font.getBestCmap().items():
        if codepoint >= 0xE000:
            by_glyph.setdefault(glyph, codepoint)
    names: dict[str, int] = {}
    reverse = {glyph: chr(cp) for cp, glyph in font.getBestCmap().items() if cp < 0xE000}
    for lookup in font['GSUB'].table.LookupList.Lookup:
        for table in lookup.SubTable:
            ligatures = getattr(table, 'ligatures', None)
            if ligatures is None and hasattr(table, 'ExtSubTable'):
                ligatures = getattr(table.ExtSubTable, 'ligatures', None)
            for first, entries in (ligatures or {}).items():
                for entry in entries:
                    parts = [first, *entry.Component]
                    if not all(part in reverse for part in parts):
                        continue
                    name = ''.join(reverse[part] for part in parts)
                    codepoint = by_glyph.get(entry.LigGlyph)
                    if codepoint is not None and name.isascii():
                        names.setdefault(name, codepoint)
    return names


def static_instance(fill: int, family: str, out: pathlib.Path) -> None:
    """A static TTF of the font at base.css's axes and the given FILL, without its ligatures."""
    font = TTFont(SOURCE)
    font.flavor = None
    static = instancer.instantiateVariableFont(font, {**AXES, 'FILL': fill})
    options = subset.Options()
    options.layout_features = []
    options.name_IDs = ['*']
    options.notdef_outline = True
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=[cp for cp in static.getBestCmap() if cp >= 0xE000])
    subsetter.subset(static)
    for record in static['name'].names:
        if record.nameID in (1, 4, 16):
            record.string = family
        elif record.nameID == 6:
            record.string = family.replace(' ', '')
    static.save(out)


def main() -> None:
    digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    names = ligature_codepoints(TTFont(SOURCE))
    static_instance(0, 'Material Symbols Outlined', ROOT / 'fonts' / 'MaterialSymbolsOutlined.ttf')
    static_instance(
        1, 'Material Symbols Outlined Filled', ROOT / 'fonts' / 'MaterialSymbolsOutlined-Filled.ttf'
    )
    entries = ';'.join(f'{name}:{cp:x}' for name, cp in sorted(names.items()))
    (ROOT / 'src' / 'glyphs.data.ts').write_text(
        '/**\n'
        ' * GENERATED by scripts/build-native-fonts.py from fonts/MaterialSymbolsOutlined.woff2; do not edit.\n'
        ' *\n'
        ' * @module\n'
        ' */\n\n'
        '/** The SHA-256 of the woff2 the glyphs were read from. */\n'
        f"export const GLYPHS_SOURCE_SHA256 = '{digest}'\n\n"
        '/** Every glyph name the font draws, as `name:codepoint-hex` entries joined by `;`. */\n'
        f"export const GLYPH_ENTRIES = '{entries}'\n"
    )
    print(f'{len(names)} glyph names; source {digest[:12]}')


main()
