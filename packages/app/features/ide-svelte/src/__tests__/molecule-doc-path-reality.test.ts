import { closeSync, existsSync, openSync, readdirSync, readSync } from 'node:fs'
import { dirname, join } from 'node:path'

import { describe, expect, it } from 'vitest'

import { moleculeDocPath } from '@molecule/app-ide-panel-logic/panels'

/**
 * Reality anchor for the doc path the find_package / read_molecule_doc cards
 * open on click — a port of
 * `@molecule/app-ide-react/src/__tests__/molecule-doc-path-reality.test.ts`
 * with the same test names and the same assertions.
 *
 * `moleculeDocPath` builds `/workspace/node_modules/@molecule/<pkg>/<doc file>`
 * from a CONSTANT filename — and the sandbox resolves that path against real
 * npm installs. When the fleet renamed the generated doc MOLECULE.md →
 * README.md (2026-08-04), this constant was missed, and every card click
 * silently opened a nonexistent file for two months: the view switched, the
 * editor stayed empty, and the unit tests kept passing because they asserted
 * the same wrong constant the code built.
 *
 * So this suite does what a string-equality test cannot: it resolves the REAL
 * installed `@molecule/*` tree (in molecule's workspace every package is
 * linked into `node_modules/@molecule/*`, and npm tarballs carry the same
 * README.md the links do), finds every doc mlcl's generator wrote there (by the
 * marker it starts each one with), and asserts each is the file `moleculeDocPath`
 * names. A doc-file rename that misses the card code now fails HERE, on every
 * push, instead of in front of users.
 *
 * A package created in this checkout and not committed yet has no generated doc
 * (the generator writes one only for packages mlcl's registry lists, which the
 * commit adds), so it has nothing to compare and is skipped. Whether every
 * package ships its README is molecule's pre-commit check, not this suite's.
 */

/** The line mlcl's doc generator starts every doc with (`mlcl/src/lib/docs-generator.ts`). */
const GENERATED_MARKER = 'AUTO-GENERATED — DO NOT EDIT THIS FILE.'

/**
 * The Markdown files at a package's root that mlcl's doc generator wrote.
 *
 * @param dir - The installed package directory.
 * @returns Their file names.
 */
function generatedDocs(dir: string): string[] {
  let names: string[]
  try {
    names = readdirSync(dir)
  } catch (error) {
    // An install running beside this test removed the package after the scope was listed: it
    // is not installed, so it carries no doc.
    if (error instanceof Error && 'code' in error && error.code === 'ENOENT') return []
    throw error
  }
  return names.filter((name) => {
    if (!name.endsWith('.md')) return false
    const fd = openSync(join(dir, name), 'r')
    try {
      const head = Buffer.alloc(512)
      const length = readSync(fd, head, 0, head.length, 0)
      return head.toString('utf8', 0, length).includes(GENERATED_MARKER)
    } finally {
      closeSync(fd)
    }
  })
}

/** Walk up from this test to the richest `node_modules/@molecule` directory. */
function resolveMoleculeScopeDir(): string | null {
  let best: { dir: string; count: number } | null = null
  let dir = import.meta.dirname
  for (;;) {
    const scope = join(dir, 'node_modules', '@molecule')
    if (existsSync(scope)) {
      const count = readdirSync(scope).length
      if (count > 0 && (best === null || count > best.count)) best = { dir: scope, count }
    }
    const parent = dirname(dir)
    if (parent === dir) break
    dir = parent
  }
  return best?.dir ?? null
}

describe('moleculeDocPath reality anchor', () => {
  it('names the doc file mlcl generates in every installed @molecule package', () => {
    const scopeDir = resolveMoleculeScopeDir()
    expect(
      scopeDir,
      'no node_modules/@molecule tree found walking up from this test — the reality ' +
        'anchor cannot run. This suite expects the molecule workspace (or a standalone ' +
        'install of this package, whose devDependencies pull real @molecule tarballs).',
    ).not.toBeNull()

    // npm stages a package it is installing under a dot-prefixed name (`.app-ui-Xk3jA2`), and
    // no package name starts with a dot.
    const entries = readdirSync(scopeDir!).filter((entry) => !entry.startsWith('.'))
    expect(entries.length).toBeGreaterThan(0)

    // The filename is taken FROM the function under test, not restated here —
    // that is the point: the code and reality are compared, never copied.
    const sample = moleculeDocPath('app-ui')
    expect(sample).not.toBeNull()
    const docFile = sample!.split('/').pop()!

    const generated = entries.map((entry) => ({
      entry,
      docs: generatedDocs(join(scopeDir!, entry)),
    }))
    // app-ui is a devDependency of this package and is always generated, so the
    // comparison below cannot pass on an empty set (a generator that stopped
    // writing the marker would leave nothing to compare).
    expect(
      generated.find(({ entry }) => entry === 'app-ui')?.docs ?? [],
      `no generated doc found in @molecule/app-ui — has mlcl's generator stopped starting docs with "${GENERATED_MARKER}"?`,
    ).not.toEqual([])
    const elsewhere = generated.filter(({ docs }) => docs.some((name) => name !== docFile))
    expect(
      elsewhere,
      `${elsewhere.length} installed @molecule packages carry a generated doc not named ${docFile} — ` +
        'the card doc path points at a file the fleet no longer ships. Update moleculeDocPath to ' +
        'the filename packages actually carry.',
    ).toEqual([])
  })

  it('opens a concrete well-known package at a path that resolves in the tree', () => {
    const scopeDir = resolveMoleculeScopeDir()
    expect(scopeDir).not.toBeNull()
    const docFile = moleculeDocPath('app-ui')!.split('/').pop()!
    // app-ui is a devDependency of this package, so it is present in every
    // install shape this suite runs in (workspace link or registry tarball).
    expect(existsSync(join(scopeDir!, 'app-ui', docFile))).toBe(true)
  })
})
