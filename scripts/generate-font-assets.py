"""Regenerate self-hosted font assets with uv run scripts/generate-font-assets.py.

From the Molecule checkout, add
--registry "$(node scripts/lib/aggregate-root.mjs)/mlcl/registry.json"
to regenerate the corresponding catalog
faces. Add --check to compare the generated bytes with the files on disk.
The upstream inputs in each bond's font-sources/ are excluded from its tarball. A font file in a
bond's shipped fonts/ that no generated face lists is refused in both modes: it reaches npm and
every app build unused (Ionicons' source .woff did, beside its generated .woff2).
"""

import argparse
from io import BytesIO
from itertools import groupby
import json
from pathlib import Path
import re
from xml.etree.ElementTree import Element, SubElement, tostring

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.ttLib.woff2 import WOFF2FlavorData
from fontTools.varLib.instancer import instantiateVariableFont


BONDS = Path(__file__).resolve().parents[1] / "packages/app/bonds/fonts"
# Latin and common punctuation, combining marks and currency used with it.
LATIN_RANGES = (
    (0x0000, 0x017F), (0x0218, 0x021B), (0x02BB, 0x02BC), (0x02C6, 0x02C6),
    (0x02DA, 0x02DA), (0x02DC, 0x02DC), (0x0300, 0x036F), (0x1E9E, 0x1E9E),
    (0x1EA0, 0x1EF9), (0x2000, 0x206F),
    (0x2074, 0x2074), (0x20A0, 0x20CF), (0x2122, 0x2122), (0x2190, 0x2199),
    (0x2212, 0x2212), (0x2215, 0x2215), (0xFEFF, 0xFEFF), (0xFFFD, 0xFFFD),
)
LATIN = {point for start, end in LATIN_RANGES for point in range(start, end + 1)}
# The former regular and bold files were HTML downloads. Use static
# instances of the same variable family, including its default optical size.
STATIC_INSTANCES = {"inter": "Inter", "jetbrains-mono": "JetBrainsMono"}


def unicode_range(points):
    ranges = []
    for _, run in groupby(enumerate(sorted(points)), lambda pair: pair[1] - pair[0]):
        values = [point for _, point in run]
        start, end = values[0], values[-1]
        ranges.append(f"U+{start:04X}" if start == end else f"U+{start:04X}-{end:04X}")
    return ", ".join(ranges)


def axes(font):
    if "fvar" not in font:
        return {}
    return {
        axis.axisTag: (axis.minValue, axis.defaultValue, axis.maxValue)
        for axis in font["fvar"].axes
    }


def confirm_subset_license(bond, font, license_text):
    """Read the bundled OFL notice and the copyright/license embedded in the input."""
    if "SIL OPEN FONT LICENSE Version 1.1" not in license_text:
        raise ValueError(f"{bond} needs a reviewed OFL 1.1 notice")
    notice = license_text.split("PREAMBLE", 1)[0]
    notices = [notice] + [
        entry.toUnicode() for entry in font["name"].names if entry.nameID in (0, 13)
    ]
    rfn = [text for text in notices if "reserved font name" in text.lower()]
    if not rfn:
        return
    # DM Serif Display already uses its own name. Source is retained in the
    # copyright and trademark notices, and never in a font identity field.
    if (
        bond == "dm-serif-display"
        and all(re.findall(r"Reserved Font Name ['‘]([^'’]+)['’]", text) == ["Source"] for text in rfn)
        and not any(
            "source" in entry.toUnicode().lower()
            for entry in font["name"].names
            if entry.nameID in (1, 3, 4, 6, 16, 18, 20, 21, 25)
        )
    ):
        return
    raise ValueError(f"{bond} declares a reserved name and must keep its original font")


def text_faces(bond, license_text):
    faces = []
    for path in sorted((bond / "font-sources").glob("*.ttf")):
        font = TTFont(path, recalcTimestamp=False)
        confirm_subset_license(bond.name, font, license_text)
        faces.append((path.stem, font))
    if bond.name in STATIC_INSTANCES:
        (source,) = (font for _, font in faces if axes(font))
        for style, weight in (("Regular", 400), ("Bold", 700)):
            location = {tag: default for tag, (_, default, _) in axes(source).items()}
            location["wght"] = weight
            instance = instantiateVariableFont(source, location, updateFontNames=True)
            faces.append((f"{STATIC_INSTANCES[bond.name]}-{style}", instance))
    return sorted(
        faces,
        key=lambda face: (
            bool(axes(face[1])), bool(face[1]["OS/2"].fsSelection & 1),
            face[1]["OS/2"].usWeightClass, face[0],
        ),
    )


def as_woff2(font, notice):
    codepoints = set(font.getBestCmap())
    variation_axes = axes(font)
    metadata = Element("metadata", version="1.0")
    SubElement(SubElement(metadata, "license"), "text").text = notice
    font.flavor = "woff2"
    font.flavorData = WOFF2FlavorData(data=font.flavorData)
    font.flavorData.metaData = tostring(metadata, encoding="utf-8", xml_declaration=True)
    buffer = BytesIO()
    font.save(buffer)
    data = buffer.getvalue()
    with TTFont(BytesIO(data)) as result:
        if set(result.getBestCmap()) != codepoints or axes(result) != variation_axes:
            raise ValueError("WOFF2 conversion changed character coverage or variation axes")
    return data


def as_latin(font, points):
    options = subset.Options()
    options.layout_features = ["*"]
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    options.name_legacy = True
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=points)
    subsetter.subset(font)
    if set(font.getBestCmap()) != points:
        raise ValueError("The Latin font's character map differs from its declared range")


def face_source(faces):
    lines = [
        "/** Font faces generated by scripts/generate-font-assets.py. */",
        "export const faces = [",
    ]
    for face in faces:
        lines += ["  {", f"    file: new URL('../fonts/{face['file']}', import.meta.url).href,"]
        for key, value in face.items():
            if key == "file":
                continue
            literal = f"'{value}'" if isinstance(value, str) else json.dumps(value)
            line = f"    {key}: {literal},"
            lines.extend([line] if len(line) <= 100 else [f"    {key}:", f"      {literal},"])
        lines.append("  },")
    return "\n".join(lines + ["]", ""])


# A font binary, as opposed to the license notices fonts/ also ships.
FONT_SUFFIXES = {".otf", ".ttf", ".woff", ".woff2"}


def generate(emit, registry, stray):
    for bond in sorted(BONDS.iterdir()):
        if not (bond / "font-sources").is_dir():
            continue
        fonts = bond / "fonts"
        faces = []
        if bond.name == "ionicons":
            notice = (fonts / "LICENSE-ionicons.txt").read_text()
            notice += (
                "\nAndroid-style icons originally built by Google’s Material Design Icons "
                "(https://github.com/google/material-design-icons), used under CC BY 4.0 "
                "(https://creativecommons.org/licenses/by/4.0/) and adapted to the Ionicons grid.\n"
            )
            with TTFont(bond / "font-sources/ionicons.woff", recalcTimestamp=False) as font:
                emit(fonts / "ionicons.woff2", as_woff2(font, notice))
            faces.append({"file": "ionicons.woff2", "weight": 400, "format": "woff2"})
        else:
            notice = (fonts / "OFL.txt").read_text()
            for stem, font in text_faces(bond, notice):
                full_file = stem + ".woff2"
                face = {"file": full_file, "weight": font["OS/2"].usWeightClass}
                if font["OS/2"].fsSelection & 1:
                    face["style"] = "italic"
                variation_axes = axes(font)
                if "wght" in variation_axes:
                    low, _, high = variation_axes["wght"]
                    face["weight"] = f"{low:g} {high:g}"
                    if bond.name == "arimo":
                        face["weight"] = "100 1000"  # Preserve the bond's declared weight range.
                if variation_axes:
                    face["variable"] = True
                face["format"] = "woff2"
                emit(fonts / full_file, as_woff2(font, notice))
                points = set(font.getBestCmap())
                latin, other = points & LATIN, points - LATIN
                if latin and other:
                    face["unicodeRange"] = unicode_range(other)
                    as_latin(font, latin)
                    if axes(font) != variation_axes:
                        raise ValueError(f"{stem}: the Latin subset lost a variation axis")
                    latin_file = stem + "-latin.woff2"
                    emit(fonts / latin_file, as_woff2(font, notice))
                    faces.append(face)
                    face = {**face, "file": latin_file, "unicodeRange": unicode_range(latin)}
                faces.append(face)
                font.close()
        emit(bond / "src/font-faces.ts", face_source(faces).encode())
        listed = {face["file"] for face in faces}
        stray.extend(
            path for path in sorted(fonts.iterdir())
            if path.suffix in FONT_SUFFIXES and path.name not in listed
        )
        if registry is not None:
            registry["packages"][f"@molecule/app-fonts-{bond.name}"]["font"]["faces"] = faces


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--registry", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    changed = []

    def emit(path, data):
        if path.is_file() and path.read_bytes() == data:
            return
        changed.append(path)
        if not args.check:
            path.write_bytes(data)

    registry = json.loads(args.registry.read_text()) if args.registry else None
    stray = []
    generate(emit, registry, stray)
    if args.registry:
        emit(args.registry, (json.dumps(registry, indent=2, ensure_ascii=False) + "\n").encode())
    if stray:
        parser.exit(
            1,
            "No face lists these shipped font files; move an input to its bond's font-sources/,"
            " or delete it:\n" + "\n".join(map(str, stray)) + "\n",
        )
    if args.check and changed:
        parser.exit(1, "Regenerate these font assets:\n" + "\n".join(map(str, changed)) + "\n")


if __name__ == "__main__":
    main()
